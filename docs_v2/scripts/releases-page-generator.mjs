// Builds the docs releases section from the repo's release notes: one page
// per version under docs_v2/releases/ plus an index listing every version
// with its excerpt. The sidebar (built in config.ts from the same source
// files) provides chronology, and prev/next follow sidebar order for free.
// Deterministic from committed files (no git), so it runs in every build,
// including shallow-clone deploys.
//   npm run sync:releases   (chained into build:docs)
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const notesDirectory = resolve(scriptDirectory, '../../releases');
const pagesDirectory = resolve(scriptDirectory, '../releases');
mkdirSync(pagesDirectory, { recursive: true });

// committed release dates (see blog-dates-generator) drive NEW badges,
// judged against build time — every deploy re-evaluates the window
const FRESH_WINDOW_SECONDS = 90 * 86_400; // three months
let releaseDates = {};
try {
  releaseDates = JSON.parse(
    readFileSync(resolve(scriptDirectory, '../releases-dates.json'), 'utf8'),
  );
} catch {}
const nowSeconds = Math.floor(Date.now() / 1000);

function formatReleaseDate(version) {
  const record = releaseDates[version];
  if (!record) return null;
  return new Date(record.date + 'T00:00:00Z').toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  });
}

const releases = readdirSync(notesDirectory)
  .filter((entry) => /^ivue@\d+\.\d+\.\d+\.md$/.test(entry))
  .map((entry) => {
    const version = entry.slice('ivue@'.length, -'.md'.length);
    return { version, parts: version.split('.').map(Number), file: entry };
  })
  .sort(
    (first, second) =>
      second.parts[0] - first.parts[0] ||
      second.parts[1] - first.parts[1] ||
      second.parts[2] - first.parts[2],
  );

const indexEntries = [];

for (const { version, file } of releases) {
  const source = readFileSync(`${notesDirectory}/${file}`, 'utf8').trim();
  // notes cross-link each other as sibling files — rewrite to page routes
  const linked = source.replace(
    /\]\(\.\/ivue@(\d+\.\d+\.\d+)(?:\.md)?\)/g,
    '](/releases/$1)',
  );
  // the excerpt: first prose paragraph after the h1, markdown stripped
  const afterTitle = linked.replace(/^# .+\n+/, '');
  const firstParagraph = afterTitle.split(/\n\s*\n/)[0] ?? '';
  const excerpt = firstParagraph
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[*_`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  indexEntries.push({ version, excerpt });

  const githubUrl = `https://github.com/infinite-system/ivue/releases/tag/ivue%40${version}`;
  // the GitHub link rides directly under the h1
  const withGithub = linked.replace(
    /^(# .+)$/m,
    `$1\n\n<a class="release-gh" href="${githubUrl}" target="_blank" rel="noreferrer">View on GitHub ↗</a>`,
  );
  const releasedOn = formatReleaseDate(version);
  const page = `---
title: 'ivue@${version}'
description: 'Release notes for ivue ${version}.'
pageClass: release-page
---

<!-- GENERATED by scripts/releases-page-generator.mjs from /releases/${file} —
     edit the note file, never this page. -->

<a class="blog-back" href="/releases/"><svg viewBox="0 0 24 24" aria-hidden="true" style="width:15px;height:15px"><path fill="currentColor" d="m10.8 12 4.9-4.9-1.4-1.4L8 12l6.3 6.3 1.4-1.4-4.9-4.9Z"/></svg>Back to Releases</a>

${withGithub}
${releasedOn ? `\n<p class="release-date">Released ${releasedOn}</p>` : ''}
`;
  writeFileSync(`${pagesDirectory}/${version}.md`, page);
}

const index = `---
title: Releases
description: 'Every ivue release with its full notes — what changed, what was measured, and how to upgrade. Generated from the release notes shipped in the repository.'
pageClass: releases-index
---

<!-- GENERATED by scripts/releases-page-generator.mjs — edit the note
     files in /releases, never this page. -->

# Releases

Every release ships its notes in the repository — these pages are
generated from them, and each is mirrored on
[GitHub Releases](https://github.com/infinite-system/ivue/releases).
Install any version with \`npm i ivue@<version>\`.

${indexEntries
  .map(
    ({ version, excerpt }, index) =>
      `## [ivue@${version}](/releases/${version})${
        index === 0 &&
        nowSeconds - (releaseDates[version]?.timestamp ?? 0) < FRESH_WINDOW_SECONDS
          ? ' <span class="new-badge">NEW</span>'
          : ''
      } <a class="release-gh release-gh--right" href="https://github.com/infinite-system/ivue/releases/tag/ivue%40${version}" target="_blank" rel="noreferrer">GitHub ↗</a> {#ivue-${version.replaceAll('.', '-')}}\n\n${excerpt}${
        formatReleaseDate(version)
          ? `\n\n<p class="release-date">Released ${formatReleaseDate(version)}</p>`
          : ''
      }`,
  )
  .join('\n\n')}
`;
writeFileSync(`${pagesDirectory}/index.md`, index);
console.log(
  `releases pages: ${releases.length} versions + index → docs_v2/releases/`,
);
