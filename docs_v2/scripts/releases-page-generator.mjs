// Assembles docs_v2/releases.md from the repo's releases/ivue@*.md notes —
// newest first, headings demoted one level so each version is an h2 anchor
// the outline picks up. Deterministic from committed files (no git), so it
// runs in every build, including shallow-clone deploys.
//   npm run sync:releases   (chained into build:docs)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const releasesDirectory = resolve(scriptDirectory, '../../releases');
const outputPath = resolve(scriptDirectory, '../releases.md');

const releases = readdirSync(releasesDirectory)
  .filter((entry) => /^ivue@\d+\.\d+\.\d+\.md$/.test(entry))
  .map((entry) => {
    const version = entry.slice('ivue@'.length, -'.md'.length);
    return { version, parts: version.split('.').map(Number), file: entry };
  })
  .sort(
    (first, second) =>
      second.parts[0] - first.parts[0] ||
      second.parts[1] - first.parts[1] ||
      second.parts[2] - first.parts[2],
  );

const sections = releases.map(({ version, file }) => {
  const source = readFileSync(`${releasesDirectory}/${file}`, 'utf8').trim();
  // demote every heading one level (h1 "# ivue@x.y.z" becomes the h2 anchor)
  let demoted = source.replace(/^(#{1,5}) /gm, '#$1 ');
  // stamp the version heading with a stable anchor regardless of its title tail
  const anchor = 'ivue-' + version.replaceAll('.', '-');
  demoted = demoted.replace(/^## (.+)$/m, `## $1 {#${anchor}}`);
  // notes cross-link each other as files — on one page they are anchors
  return demoted.replace(
    /\]\(\.\/ivue@(\d+)\.(\d+)\.(\d+)(?:\.md)?\)/g,
    '](#ivue-$1-$2-$3)',
  );
});

const page = `---
title: Releases
description: 'Every ivue release with its full notes — what changed, what was measured, and how to upgrade. Generated from the release notes shipped in the repository.'
outline: [2, 2]
---

<!-- GENERATED by scripts/releases-page-generator.mjs from /releases —
     edit the release note files, never this page. -->

# Releases

Every release ships its notes in the repository
([\`releases/\`](https://github.com/infinite-system/ivue/tree/main/releases)) —
this page is generated from them. Install any version:
\`npm i ivue@<version>\`.

${sections.join('\n\n---\n\n')}
`;

writeFileSync(outputPath, page);
console.log(`releases page: ${releases.length} versions → docs_v2/releases.md`);
